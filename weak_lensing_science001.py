def reproduce_regression_baseline(executable_hashes: dict) -> dict:
    """Reproduce the frozen regression baseline for Abell 2744.

    The recorded SHA `80d8fe47bd0d45672e16c659fc1b095114106eacd6a52634fccde1fc81b41b3f`
    was produced by NUMERICAL-CONVERGENCE-001 Group A at the default
    configuration (128² grid, Δs step, 80 steps, 20 000 photons).
    """
    cluster = CLUSTERS[0]

    cfg_recorded = REGRESSION_BASELINE_CONFIG
    print(f"\n[Regression] Reproducing recorded baseline SHA for {cluster['label']} "
          f"@ nphotons={cfg_recorded['nphotons']}, grid={cfg_recorded['grid_n']}^2, "
          f"step={cfg_recorded['step']} (the configuration that produced the "
          f"recorded SHA)")
    prod_recorded = run_production(cluster, cfg_recorded, executable_hashes)
    pred_recorded = predict_maps(prod_recorded)

    pk = pred_recorded["kappa"][np.isfinite(pred_recorded["kappa"])]
    finite_kappa_rms = float(np.sqrt(np.mean(pk ** 2)))
    pg = pred_recorded["gamma_mag"][np.isfinite(pred_recorded["gamma_mag"])]
    finite_gamma_rms = float(np.sqrt(np.mean(pg ** 2)))

    traj_sha = prod_recorded["trajectory_sha256"]
    cons_max = float(np.max(prod_recorded["photons"]["conservation"]))

    baseline = EXPECTED_REGRESSION_20K
    rmse_kappa_pct = abs(finite_kappa_rms - baseline["kappa_rms"]) / baseline["kappa_rms"] * 100.0
    rmse_gamma_pct = abs(finite_gamma_rms - baseline["gamma_rms"]) / baseline["gamma_rms"] * 100.0
    mean_kappa_abs_diff = abs(float(pk.mean()) - baseline["kappa_mean"])
    sha_match = traj_sha == baseline["trajectory_sha256"]
    cons_match = cons_max <= baseline["conservation_max"]

    print(f"\n[Regression] Cross-checking minimum production config "
          f"({MIN_PRODUCTION['grid_n']}^2, Δs/2) for Abell 2744 ...")
    prod_min = run_production(cluster, MIN_PRODUCTION, executable_hashes)
    pred_min = predict_maps(prod_min)
    pk_min = pred_min["kappa"][np.isfinite(pred_min["kappa"])]
    pg_min = pred_min["gamma_mag"][np.isfinite(pred_min["gamma_mag"])]
    finite_kappa_rms_min = float(np.sqrt(np.mean(pk_min ** 2)))
    finite_gamma_rms_min = float(np.sqrt(np.mean(pg_min ** 2)))
    rmse_kappa_pct_min = abs(finite_kappa_rms_min - baseline["kappa_rms"]) / baseline["kappa_rms"] * 100.0
    rmse_gamma_pct_min = abs(finite_gamma_rms_min - baseline["gamma_rms"]) / baseline["gamma_rms"] * 100.0

    ok = (rmse_kappa_pct <= 1.0 and rmse_gamma_pct <= 1.0
          and mean_kappa_abs_diff <= 0.01 and sha_match and cons_match)

    return {
        "trajectory_sha256_reproduced": traj_sha,
        "trajectory_sha256_expected": baseline["trajectory_sha256"],
        "sha_match": bool(sha_match),
        "kappa_rms_reproduced": finite_kappa_rms,
        "kappa_rms_expected": baseline["kappa_rms"],
        "kappa_rms_relative_change_percent": rmse_kappa_pct,
        "kappa_peak_abs_reproduced": float(np.max(np.abs(pk))),
        "kappa_peak_abs_expected": baseline["kappa_peak_abs"],
        "kappa_mean_reproduced": float(pk.mean()),
        "kappa_mean_expected": baseline["kappa_mean"],
        "kappa_mean_absolute_change": mean_kappa_abs_diff,
        "kappa_std_reproduced": float(pk.std()),
        "kappa_std_expected": baseline["kappa_std"],
        "gamma_rms_reproduced": finite_gamma_rms,
        "gamma_rms_expected": baseline["gamma_rms"],
        "gamma_rms_relative_change_percent": rmse_gamma_pct,
        "conservation_max_reproduced": cons_max,
        "conservation_max_expected": baseline["conservation_max"],
        "conservation_match": bool(cons_match),
        "minimum_production_cross_check": {
            "grid_n": MIN_PRODUCTION["grid_n"],
            "step": MIN_PRODUCTION["step"],
            "kappa_rms": finite_kappa_rms_min,
            "gamma_rms": finite_gamma_rms_min,
            "kappa_rms_relative_change_percent": rmse_kappa_pct_min,
            "gamma_rms_relative_change_percent": rmse_gamma_pct_min,
            "within_1pct_tolerance":
                rmse_kappa_pct_min <= 1.0 and rmse_gamma_pct_min <= 1.0,
        },
        "reproduction_ok": bool(ok),
        "runtime_propagation_seconds": prod_recorded["propagation_seconds"],
        "runtime_extraction_seconds": prod_recorded["extraction_seconds"],
        "baseline_configuration_actually_used": cfg_recorded,
        "baseline_metadata_records": {
            "grid_n": 256,
            "step": 0.03,
            "steps": 160,
            "note": "regression_baseline.json labels the SHA as 'production_20k' "
                    "with grid_n=256 but the recorded SHA was actually produced "
                    "at grid_n=128 (NUMERICAL-CONVERGENCE-001 Group A default).",
        },
    }


def process_cluster_production(cluster: dict, cfg: dict,
                                executable_hashes: dict) -> dict:
    """Run a single production configuration on one cluster, return all outputs."""
    prod = run_production(cluster, cfg, executable_hashes)
    pred = predict_maps(prod)
    obs = load_observation_full(cluster)
    obs_grid = resample_observation(obs, cfg["bins"], cfg["extent"])
    comparison = compare_predictions(pred, obs_grid, cfg["bins"])
    residuals = {
        "kappa": residual_map(pred["kappa"], obs_grid["kappa"]),
        "gamma1": residual_map(pred["gamma1"], obs_grid["gamma1"]),
        "gamma2": residual_map(pred["gamma2"], obs_grid["gamma2"]),
        "gamma_mag": residual_map(pred["gamma_mag"], obs_grid["gamma"]),
    }
    profiles = {
        "kappa": {
            "r": azimuthal_average(obs_grid["kappa"], cfg["extent"])[0],
            "predicted": azimuthal_average(pred["kappa"], cfg["extent"])[1],
            "observed": azimuthal_average(obs_grid["kappa"], cfg["extent"])[1],
        },
        "gamma_mag": {
            "r": azimuthal_average(obs_grid["gamma"], cfg["extent"])[0],
            "predicted": azimuthal_average(pred["gamma_mag"], cfg["extent"])[1],
            "observed": azimuthal_average(obs_grid["gamma"], cfg["extent"])[1],
        },
    }
    ts = tangential_shear(pred["gamma1"], pred["gamma2"],
                           obs_grid["gamma1"], obs_grid["gamma2"], cfg["extent"])
    morpho = morphology_labels(prod["field"], obs_grid, pred, cfg["extent"])
    return {
        "cluster_id": cluster["id"],
        "cluster_label": cluster["label"],
        "config_label": cfg["label"],
        "production": prod,
        "predictions": pred,
        "obs_grid": obs_grid,
        "obs_files": obs["files"],
        "obs_shas": obs["shas"],
        "comparison": comparison,
        "residuals": residuals,
        "profiles": profiles,
        "tangential_shear": ts,
        "morphology": morpho,
    }


