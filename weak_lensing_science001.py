def azimuthal_average(field: np.ndarray, extent: float, n_bins: int = 24) -> tuple[np.ndarray, np.ndarray]:
    """Azimuthal mean of a 2D map, returned as (bin_centres, mean_values).

    Bin centres are physical radii r in [0, sqrt(2) * extent].
    """
    n = field.shape[0]
    coords = np.linspace(-extent, extent, n)
    X, Y = np.meshgrid(coords, coords, indexing="xy")
    r = np.hypot(X, Y).ravel()
    vals = field.ravel()
    mask = np.isfinite(vals)
    r = r[mask]; vals = vals[mask]
    edges = np.linspace(0.0, np.sqrt(2) * extent, n_bins + 1)
    centres = 0.5 * (edges[:-1] + edges[1:])
    sums = np.zeros(n_bins)
    counts = np.zeros(n_bins, dtype=int)
    idx = np.clip(np.searchsorted(edges, r) - 1, 0, n_bins - 1)
    for k in range(n_bins):
        sel = idx == k
        if sel.any():
            sums[k] = vals[sel].sum()
            counts[k] = sel.sum()
    means = np.where(counts > 0, sums / np.maximum(counts, 1), np.nan)
    return centres, means


def tangential_shear(pred_g1: np.ndarray, pred_g2: np.ndarray,
                     obs_g1: np.ndarray, obs_g2: np.ndarray,
                     extent: float, n_bins: int = 24) -> dict:
    """Compute azimuthal tangential shear for predicted and observed maps."""
    n = pred_g1.shape[0]
    coords = np.linspace(-extent, extent, n)
    X, Y = np.meshgrid(coords, coords, indexing="xy")
    r = np.hypot(X, Y)
    phi = np.arctan2(Y, X)

    def gt(g1, g2):
        g1 = np.where(np.isfinite(g1), g1, 0.0)
        g2 = np.where(np.isfinite(g2), g2, 0.0)
        return -(g1 * np.cos(2 * phi) + g2 * np.sin(2 * phi))

    pred_gt = gt(pred_g1, pred_g2)
    obs_gt = gt(obs_g1, obs_g2)

    edges = np.linspace(0.0, np.sqrt(2) * extent, n_bins + 1)
    centres = 0.5 * (edges[:-1] + edges[1:])
    r_flat = r.ravel()

    def avg(field):
        f = field.ravel()
        idx = np.clip(np.searchsorted(edges, r_flat) - 1, 0, n_bins - 1)
        sums = np.zeros(n_bins); counts = np.zeros(n_bins, dtype=int)
        for k in range(n_bins):
            sel = idx == k
            if sel.any():
                sums[k] = f[sel].sum(); counts[k] = sel.sum()
        return np.where(counts > 0, sums / np.maximum(counts, 1), np.nan)

    return {
        "r": centres,
        "predicted_gt": avg(pred_gt),
        "observed_gt": avg(obs_gt),
    }


def morphology_labels(field: dict, obs_grid: dict, pred: dict,
                      extent: float) -> dict:
    """Quantitative structural labels.

    The frozen laboratory outputs are dimensionless lensing-like fields on a
    pipeline grid [-extent, extent]^2.  The "core", "intermediate", "outer
    halo" labels refer to radial annuli in pipeline units.  No physical
    interpretation is attached.
    """
    rho = field["rho"]
    n = rho.shape[0]
    coords = np.linspace(-extent, extent, n)
    X_rho, Y_rho = np.meshgrid(coords, coords, indexing="xy")
    r_rho = np.hypot(X_rho, Y_rho)
    rho_max = float(rho.max())
    core_mask = (r_rho <= 1.5) & (rho >= 0.5 * rho_max)
    intermediate_mask = (r_rho > 1.5) & (r_rho <= 4.0) & (rho >= 0.05 * rho_max)
    halo_mask = (r_rho > 4.0) & (r_rho <= 6.0) & (rho >= 0.01 * rho_max)
    filament_mask = (r_rho > 3.0) & (rho < 0.1 * rho_max) & (rho > 0.0)
    n_core = int(core_mask.sum())
    n_intermediate = int(intermediate_mask.sum())
    n_halo = int(halo_mask.sum())
    n_filament = int(filament_mask.sum())
    centroid_rho = np.array([
        (X_rho * rho).sum() / max(rho.sum(), 1e-30),
        (Y_rho * rho).sum() / max(rho.sum(), 1e-30),
    ])
    second_moment = np.array([
        ((X_rho - centroid_rho[0]) ** 2 * rho).sum() / max(rho.sum(), 1e-30),
        ((Y_rho - centroid_rho[1]) ** 2 * rho).sum() / max(rho.sum(), 1e-30),
        ((X_rho - centroid_rho[0]) * (Y_rho - centroid_rho[1]) * rho).sum() /
            max(rho.sum(), 1e-30),
    ])
    eigvals, _ = np.linalg.eigh(np.array([
        [second_moment[0], second_moment[2]],
        [second_moment[2], second_moment[1]],
    ]))
    semi_major = float(np.sqrt(max(eigvals[1], 0.0)))
    semi_minor = float(np.sqrt(max(eigvals[0], 0.0)))
    elongation = semi_major / max(semi_minor, 1e-30) if semi_minor > 0 else float("inf")
    peak_r = float(rho.max())
    centroid_r = float(np.hypot(*centroid_rho))

    obs_kappa = np.where(np.isfinite(obs_grid["kappa"]), obs_grid["kappa"], 0.0)
    n_obs = obs_kappa.shape[0]
    coords_obs = np.linspace(-extent, extent, n_obs)
    X_obs, Y_obs = np.meshgrid(coords_obs, coords_obs, indexing="xy")
    obs_centroid = np.array([
        (X_obs * obs_kappa).sum() / max(obs_kappa.sum(), 1e-30),
        (Y_obs * obs_kappa).sum() / max(obs_kappa.sum(), 1e-30),
    ])
    obs_second = np.array([
        ((X_obs - obs_centroid[0]) ** 2 * obs_kappa).sum() /
            max(obs_kappa.sum(), 1e-30),
        ((Y_obs - obs_centroid[1]) ** 2 * obs_kappa).sum() /
            max(obs_kappa.sum(), 1e-30),
        ((X_obs - obs_centroid[0]) * (Y_obs - obs_centroid[1]) * obs_kappa).sum() /
            max(obs_kappa.sum(), 1e-30),
    ])
    obs_eigvals, _ = np.linalg.eigh(np.array([
        [obs_second[0], obs_second[2]],
        [obs_second[2], obs_second[1]],
    ]))
    obs_semi_major = float(np.sqrt(max(obs_eigvals[1], 0.0)))
    obs_semi_minor = float(np.sqrt(max(obs_eigvals[0], 0.0)))
    obs_elongation = obs_semi_major / max(obs_semi_minor, 1e-30) if obs_semi_minor > 0 else float("inf")

    pred_kappa_safe = np.where(np.isfinite(pred["kappa"]), pred["kappa"], 0.0)
    pk_sum = float(pred_kappa_safe.sum())
    if pk_sum > 1e-15:
        pred_centroid = np.array([
            (X_obs * pred_kappa_safe).sum() / pk_sum,
            (Y_obs * pred_kappa_safe).sum() / pk_sum,
        ])
        pred_centroid_offset = float(np.hypot(*pred_centroid))
    else:
        pred_centroid_offset = float("nan")

    return {
        "rho_peak_pipeline_units": peak_r,
        "rho_centroid_offset_pipeline_units": centroid_r,
        "rho_semi_major_pipeline_units": semi_major,
        "rho_semi_minor_pipeline_units": semi_minor,
        "rho_elongation": elongation,
        "observed_kappa_semi_major": obs_semi_major,
        "observed_kappa_semi_minor": obs_semi_minor,
        "observed_kappa_elongation": obs_elongation,
        "predicted_kappa_centroid_offset": pred_centroid_offset,
        "n_core_pixels": n_core,
        "n_intermediate_pixels": n_intermediate,
        "n_halo_pixels": n_halo,
        "n_filament_pixels": n_filament,
        "core_fraction": float(n_core / max(n_core + n_intermediate + n_halo + n_filament, 1)),
        "halo_fraction": float(n_halo / max(n_core + n_intermediate + n_halo + n_filament, 1)),
        "filament_fraction": float(n_filament / max(n_core + n_intermediate + n_halo + n_filament, 1)),
    }


