def outcome_statement(results: dict) -> str:
    """Produce Outcome A or Outcome B statement."""
    pe = np.array([d["comparison"]["kappa"]["pearson_correlation"]
                   for d in results.values()])
    pg = np.array([d["comparison"]["gamma_mag"]["pearson_correlation"]
                   for d in results.values()])
    ssim_k = np.array([d["comparison"]["kappa"]["ssim"] for d in results.values()])
    ssim_g = np.array([d["comparison"]["gamma_mag"]["ssim"] for d in results.values()])
    rms_k = np.array([d["comparison"]["kappa"]["rms_error"] for d in results.values()])
    observable_dynamic_k = np.array([
        float(np.nanstd(d["obs_grid"]["kappa"])) for d in results.values()])
    rel_rms_k = rms_k / np.maximum(observable_dynamic_k, 1e-15)

    kappa_biases = []
    for d in results.values():
        r = d["residuals"]["kappa"]
        rf = r[np.isfinite(r)]
        kappa_biases.append(float(np.mean(rf)) if rf.size else 0.0)
    bias_mean = float(np.mean(kappa_biases))
    bias_std = float(np.std(kappa_biases))

    sign_consistency = sum(1 for b in kappa_biases if np.sign(b) == np.sign(bias_mean))
    n_positive_pearson = int(np.sum(pe > 0))
    median_pearson = float(np.nanmedian(pe))
    median_ssim = float(np.nanmedian(ssim_k))

    has_strong_agreement = (
        median_pearson >= 0.3
        and median_ssim >= 0.1
    )
    has_weak_agreement = (
        median_pearson >= 0.05
        or median_ssim >= 0.05
    )
    has_systematic_bias = abs(bias_mean) > 0.01 and sign_consistency >= 4

    if has_strong_agreement and not has_systematic_bias:
        return (f"**Outcome A (strong)** - the frozen Version A laboratory "
                f"reproduces measurable aspects of the observed "
                f"weak-lensing structure across the benchmark sample "
                f"(median Pearson κ = {median_pearson:+.4f}, median SSIM "
                f"κ = {median_ssim:+.4f}).  Aggregate κ bias "
                f"= {bias_mean:+.5f} ± {bias_std:.5f} (not "
                f"systematically signed).  The frozen laboratory is not "
                f"modified.")
    if has_weak_agreement and not has_systematic_bias:
        return (f"**Outcome A (weak)** - weak but measurable agreement "
                f"with the observed weak-lensing structure across the "
                f"benchmark sample (median Pearson κ = {median_pearson:+.4f}, "
                f"median SSIM κ = {median_ssim:+.4f}, "
                f"{n_positive_pearson}/5 clusters show positive Pearson κ). "
                f"Aggregate κ bias = {bias_mean:+.5f} ± {bias_std:.5f}. "
                f"The frozen laboratory is not modified; any residual "
                f"disagreement is documented quantitatively.")
    return (f"**Outcome B** - agreement is limited.  Median Pearson κ "
            f"= {median_pearson:+.4f}, median SSIM κ = "
            f"{median_ssim:+.4f}.  Aggregate κ bias "
            f"= {bias_mean:+.5f} ± {bias_std:.5f} with {sign_consistency}/5 "
            f"clusters sharing the same sign ({'systematic' if sign_consistency >= 4 else 'partial'}). "
            f"The frozen Version A laboratory is not modified.  "
            f"Recurring residual patterns are documented in "
            f"`residual_statistics.csv`, `cluster_comparison.csv`, and "
            f"the per-cluster residual maps.  Future improvements shall "
            f"be investigated through Version B physics, not by altering "
            f"the frozen Version 1 laboratory.")


