def _radial_kappa_residual(pred_kappa: np.ndarray, obs_kappa: np.ndarray,
                            extent: float) -> tuple[np.ndarray, np.ndarray]:
    n = pred_kappa.shape[0]
    coords = np.linspace(-extent, extent, n)
    X, Y = np.meshgrid(coords, coords, indexing="xy")
    r = np.hypot(X, Y).ravel()
    res = (pred_kappa - obs_kappa).ravel()
    mask = np.isfinite(res)
    r = r[mask]; res = res[mask]
    edges = np.linspace(0.0, np.sqrt(2) * extent, 12)
    centres = 0.5 * (edges[:-1] + edges[1:])
    sums = np.zeros(len(centres)); counts = np.zeros(len(centres), dtype=int)
    idx = np.clip(np.searchsorted(edges, r) - 1, 0, len(centres) - 1)
    for k in range(len(centres)):
        sel = idx == k
        if sel.any():
            sums[k] = res[sel].sum(); counts[k] = sel.sum()
    means = np.where(counts > 0, sums / np.maximum(counts, 1), np.nan)
    return centres, means


