def save_map(out_path: Path, array: np.ndarray, title: str,
             cmap: str = "viridis", symmetric: bool = False,
             extent: tuple = (-8, 8, -8, 8), vmax_abs: float | None = None) -> None:
    fig, ax = plt.subplots(figsize=(7, 6))
    if symmetric:
        finite = array[np.isfinite(array)]
        vmax_abs = float(np.max(np.abs(finite))) if finite.size else 1.0
        im = ax.imshow(array, origin="lower", extent=list(extent),
                       cmap=cmap, vmin=-vmax_abs, vmax=vmax_abs)
    else:
        im = ax.imshow(array, origin="lower", extent=list(extent), cmap=cmap)
    ax.set(xlabel="x", ylabel="y", title=title, aspect="equal")
    fig.colorbar(im, ax=ax)
    fig.tight_layout()
    fig.savefig(out_path, dpi=130)
    plt.close(fig)


def save_three_panel(out_path: Path, obs: np.ndarray, pred: np.ndarray,
                     residual: np.ndarray, title: str,
                     cmap: str = "RdBu_r") -> None:
    finite = np.concatenate([obs[np.isfinite(obs)].ravel(),
                             pred[np.isfinite(pred)].ravel()])
    vmax_abs = float(np.max(np.abs(finite))) if finite.size else 1.0
    fig, axes = plt.subplots(1, 3, figsize=(18, 5.5))
    for ax, arr, label in zip(
        axes,
        [obs, pred, residual],
        ["Observed", "Predicted (frozen Version A)", "Residual (Pred - Obs)"],
    ):
        im = ax.imshow(arr, origin="lower", extent=[-8, 8, -8, 8],
                       cmap=cmap, vmin=-vmax_abs, vmax=vmax_abs)
        ax.set(xlabel="x", ylabel="y",
               title=f"{label}\n{vmax_abs:.3f}", aspect="equal")
        fig.colorbar(im, ax=ax)
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(out_path, dpi=130)
    plt.close(fig)


